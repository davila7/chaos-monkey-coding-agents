"""The crates in crates/: .crate archives, a cargo local-registry mirror, vendor/ and Cargo.lock.

vendor/ follows `cargo vendor` of cargo 1.65 (one directory per crate, `.cargo-checksum.json`
with the sha256 of every file and of the .crate archive); Cargo.lock follows lock file version 3.
Both are checked against the real cargo in the task image, which reports nothing to change on
the reference tree.
"""

from __future__ import annotations

import gzip
import hashlib
import io
import json
import tarfile
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
CRATES = HERE / "crates"
REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"
TAR_MTIME = 1767225600  # 2026-01-01T00:00:00Z


def versions(name: str) -> list[str]:
    return sorted((p.name for p in (CRATES / name).iterdir()), key=lambda v: tuple(int(x) for x in v.split(".")))


def files(name: str, ver: str) -> dict[str, bytes]:
    root = CRATES / name / ver
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in sorted(root.rglob("*")) if p.is_file()}


def crate_archive(name: str, ver: str) -> bytes:
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.USTAR_FORMAT) as tar:
        for rel, data in sorted(files(name, ver).items()):
            info = tarfile.TarInfo(f"{name}-{ver}/{rel}")
            info.size, info.mtime, info.mode = len(data), TAR_MTIME, 0o644
            tar.addfile(info, io.BytesIO(data))
    out = io.BytesIO()
    with gzip.GzipFile(fileobj=out, mode="wb", mtime=0, compresslevel=9) as gz:
        gz.write(raw.getvalue())
    return out.getvalue()


def checksum(name: str, ver: str) -> str:
    return hashlib.sha256(crate_archive(name, ver)).hexdigest()


def manifest(name: str, ver: str) -> dict:
    return tomllib.loads(files(name, ver)["Cargo.toml"].decode())


def index_path(name: str) -> str:
    n = name.lower()
    if len(n) <= 2:
        return f"{len(n)}/{n}"
    if len(n) == 3:
        return f"3/{n[0]}/{n}"
    return f"{n[:2]}/{n[2:4]}/{n}"


def write_mirror(out: Path) -> None:
    for crate in sorted(p.name for p in CRATES.iterdir()):
        lines = []
        for ver in versions(crate):
            features = manifest(crate, ver).get("features", {})
            entry = {"name": crate, "vers": ver, "deps": [], "cksum": checksum(crate, ver),
                     "features": features, "yanked": False}
            lines.append(json.dumps(entry, separators=(",", ":")))
            (out / f"{crate}-{ver}.crate").parent.mkdir(parents=True, exist_ok=True)
            (out / f"{crate}-{ver}.crate").write_bytes(crate_archive(crate, ver))
        p = out / "index" / index_path(crate)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text("".join(line + "\n" for line in lines))


def write_vendor(root: Path, locked: dict[str, str]) -> None:
    for crate, ver in sorted(locked.items()):
        dest = root / "vendor" / crate
        sums = {}
        for rel, data in files(crate, ver).items():
            p = dest / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(data)
            sums[rel] = hashlib.sha256(data).hexdigest()
        doc = {"files": sums, "package": checksum(crate, ver)}
        (dest / ".cargo-checksum.json").write_text(json.dumps(doc, sort_keys=True, separators=(",", ":")))


def cargo_lock(members: dict[str, tuple[str, list[str]]], locked: dict[str, str]) -> str:
    """members: name -> (version, dependency names); locked: registry crate -> version."""
    packages = []
    for name, (ver, deps) in members.items():
        packages.append((name, ver, None, sorted(deps)))
    for name, ver in locked.items():
        packages.append((name, ver, checksum(name, ver), []))
    out = ["# This file is automatically @generated by Cargo.", "# It is not intended for manual editing.", "version = 3"]
    for name, ver, cksum, deps in sorted(packages):
        out += ["", "[[package]]", f'name = "{name}"', f'version = "{ver}"']
        if cksum:
            out += [f'source = "{REGISTRY}"', f'checksum = "{cksum}"']
        if deps:
            out += ["dependencies = ["] + [f' "{d}",' for d in deps] + ["]"]
    return "\n".join(out) + "\n"
